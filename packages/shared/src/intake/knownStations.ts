export function isKnownTrainStationName(name: string): boolean {
  const raw = name.trim();
  if (!raw) return false;
  if (KNOWN_TRAIN_STATIONS.has(raw)) return true;
  if (raw.endsWith("站") && KNOWN_TRAIN_STATIONS.has(raw.slice(0, -1))) return true;
  return false;
}
